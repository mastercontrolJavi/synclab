import { AbsoluteFill, Audio, Sequence, interpolate, staticFile, useCurrentFrame } from "remotion";

import { Backdrop } from "./components/Backdrop";
import { loadFonts } from "./fonts";
import { Close } from "./scenes/Close";
import { Concepts } from "./scenes/Concepts";
import { Hook } from "./scenes/Hook";
import { Meet } from "./scenes/Meet";
import { Tradeoff } from "./scenes/Tradeoff";
import { color } from "./theme";
import timeline from "./timeline.json";

loadFonts();

const { fps, cues, durationSec } = timeline;
const f = (seconds: number) => Math.round(seconds * fps);
export const DURATION = f(durationSec);

const ACTS = [
  { name: "Hook", from: f(cues.hook), to: f(cues.meet), Scene: Hook },
  { name: "Meet SyncLab", from: f(cues.meet), to: f(cues.prediction), Scene: Meet },
  { name: "Concepts", from: f(cues.prediction), to: f(cues.conditions), Scene: Concepts },
  { name: "Tradeoff", from: f(cues.conditions), to: f(cues.close), Scene: Tradeoff },
  { name: "Close", from: f(cues.close), to: DURATION, Scene: Close },
] as const;

export function Launch() {
  const frame = useCurrentFrame();
  const fadeIn = interpolate(frame, [0, 14], [1, 0], { extrapolateRight: "clamp" });
  return (
    <AbsoluteFill style={{ background: color.surface0 }}>
      <Backdrop />
      {ACTS.map(({ name, from, to, Scene }) => (
        <Sequence key={name} name={name} from={from} durationInFrames={to - from}>
          <Scene />
        </Sequence>
      ))}
      <AbsoluteFill style={{ background: "black", opacity: fadeIn, pointerEvents: "none" }} />

      {/* Original score + sound design, generated by music/compose.py. Replace music.wav to swap the track. */}
      <Audio src={staticFile("audio/music.wav")} volume={0.8} />
      <Audio src={staticFile("audio/sfx.wav")} volume={0.55} />
    </AbsoluteFill>
  );
}
